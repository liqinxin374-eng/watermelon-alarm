function formatDateKey(year: number, month: number, day: number): string {
  const m = String(month).padStart(2, '0');
  const d = String(day).padStart(2, '0');
  return `${year}-${m}-${d}`;
}

/**
 * 注册或更新自定义节假日与调休补班数据（支持动态从远程配置更新）
 */
export function registerCustomHolidays(holidays: string[] = [], makeupWorkdays: string[] = []): void {
  for (const h of holidays) HOLIDAYS_SET.add(h);
  for (const w of makeupWorkdays) MAKEUP_WORKDAYS_SET.add(w);
}

/**
 * 判断指定日期是否为工作日
 * @param year  年
 * @param month 月 (1-12)
 * @param day   日 (1-31)
 * @param mode  'china'（法定工作日，包含调休智能判断） | 'standard'（普通周一至周五）
 */
export function isWorkday(year: number, month: number, day: number, mode: WorkdayMode = 'china'): boolean {
  // 计算星期几（0=周日, 1=周一, ..., 6=周六）
  const weekday = new Date(Date.UTC(year, month - 1, day)).getUTCDay();
  const isWeekend = weekday === 0 || weekday === 6;

  if (mode === 'standard') {
    return !isWeekend;
  }

  // 中国法定工作日模式
  const dateKey = formatDateKey(year, month, day);

  // 1. 若在调休补班日表中 -> 必定是工作日（即使是周六/周日）
  if (MAKEUP_WORKDAYS_SET.has(dateKey)) {
    return true;
  }

  // 2. 若在法定节假日放假表中 -> 必定是非工作日（即使是周一至周五）
  if (HOLIDAYS_SET.has(dateKey)) {
    return false;
  }

  // 3. 常规周一至周五为工作日
  return !isWeekend;
}

/**
 * 判断指定日期是否为周末或法定节假日
 */
export function isWeekendOrHoliday(year: number, month: number, day: number, mode: WorkdayMode = 'china'): boolean {
  return !isWorkday(year, month, day, mode);
}
